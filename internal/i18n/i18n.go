func Normalize(locale string) string {
	if strings.EqualFold(strings.TrimSpace(locale), Vietnamese) {
		return Vietnamese
	}
	return English
}

func T(locale, key string) string {
	locale = Normalize(locale)
	if value := translations[locale][key]; value != "" {
		return value
	}
	return key
}
